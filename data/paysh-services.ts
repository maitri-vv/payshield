export interface PayShService {
  id: string
  name: string
  provider: string
  slug: string
  category: PayShCategory
  endpoints: number
  paysh_price_min: number
  paysh_price_max: number
  paysh_price_label: string
  status: "free tier" | "metered"
  description: string
  models_included: string[]
  direct_alternative: string
  direct_cost_monthly: number
  direct_cost_label: string
  direct_requires: string[]
  break_even_requests: number
  best_for: string
  paysh_advantage: string
  savings_low_volume: string
  savings_high_volume: string
  paysh_url: string
}

const payShUrl = (slug: string) => `https://pay.sh/${slug}`

